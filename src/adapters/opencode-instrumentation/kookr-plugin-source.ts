/**
 * Generates the text of the Kookr hook-emitter plugin for opencode 1.19.x
 * (RFC rfc-opencode-agent-integration §4). The plugin is plain ESM JavaScript
 * (no imports except node: builtins) dropped into
 * `$OPENCODE_CONFIG_DIR/plugins/kookr.js`. It translates opencode events into
 * Claude-shaped hook payloads and pipes them to `kookr-hook-writer.js` via
 * `/bin/sh -c <hookCommand>`, so HookIngestion needs no changes.
 *
 * Safety: every emit is fail-open (never throws), bounded to ~2s, and the
 * child is unref'd.
 */
export interface ClaudeHookGroup {
  matcher?: string;
  hooks: { type: 'command'; command: string; timeout?: number }[];
}

/** Claude settings.json hook shape; run by the plugin with Claude semantics. */
export interface ClaudeHooksConfig {
  /** Extra env for hook commands (e.g. CLAUDE_PLUGIN_ROOT). */
  env?: Record<string, string>;
  hooks: {
    SessionStart?: ClaudeHookGroup[];
    PreToolUse?: ClaudeHookGroup[];
    PostToolUse?: ClaudeHookGroup[];
    Stop?: ClaudeHookGroup[];
  };
}

export const MAX_STOP_REPROMPTS = 4;

export interface KookrPluginSourceOptions {
  claudeHooks?: ClaudeHooksConfig;
  /** Shell command that reads one JSON payload on stdin (see buildHookCommand). */
  hookCommand: string;
  sessionId: string;
  cwd: string;
}

export function buildKookrPluginSource(opts: KookrPluginSourceOptions): string {
  const cfg = JSON.stringify({
    hookCommand: opts.hookCommand,
    sessionId: opts.sessionId,
    cwd: opts.cwd,
    claudeHooks: opts.claudeHooks ?? null,
    maxStopReprompts: MAX_STOP_REPROMPTS,
  });
  return `// Generated by Kookr. Do not edit.
import { spawn } from 'node:child_process';
import { appendFileSync } from 'node:fs';

const CFG = ${cfg};
const EMIT_TIMEOUT_MS = 2000;

function debug(record) {
  const file = process.env.KOOKR_OPENCODE_PLUGIN_DEBUG;
  if (!file) return;
  try {
    appendFileSync(file, JSON.stringify({ ts: Date.now(), ...record }) + '\\n');
  } catch {
    /* ignore */
  }
}

function emit(payload) {
  return new Promise((resolve) => {
    let done = false;
    const finish = () => {
      if (done) return;
      done = true;
      resolve();
    };
    try {
      const child = spawn('/bin/sh', ['-c', CFG.hookCommand], {
        stdio: ['pipe', 'ignore', 'ignore'],
      });
      const timer = setTimeout(() => {
        try { child.kill('SIGKILL'); } catch { /* ignore */ }
        finish();
      }, EMIT_TIMEOUT_MS);
      timer.unref();
      child.on('error', finish);
      child.on('close', () => { clearTimeout(timer); finish(); });
      child.stdin.on('error', () => {});
      child.stdin.end(JSON.stringify(payload));
      child.unref();
    } catch (err) {
      debug({ emitError: String(err) });
      finish();
    }
  });
}

function runCmd(command, payload, timeoutSec) {
  return new Promise((resolve) => {
    let done = false;
    let stdout = '';
    let stderr = '';
    const finish = (code) => {
      if (done) return;
      done = true;
      resolve({ code, stdout, stderr });
    };
    try {
      const ch = CFG.claudeHooks || {};
      const child = spawn('/bin/sh', ['-c', command], {
        stdio: ['pipe', 'pipe', 'pipe'],
        cwd: CFG.cwd,
        env: { ...process.env, ...(ch.env || {}), CLAUDE_PROJECT_DIR: CFG.cwd },
      });
      const timer = setTimeout(() => {
        try { child.kill('SIGKILL'); } catch { /* ignore */ }
        debug({ hookTimeout: command });
        finish(null);
      }, (timeoutSec || 60) * 1000);
      child.stdout.on('data', (d) => { stdout += d; });
      child.stderr.on('data', (d) => { stderr += d; });
      child.on('error', (e) => { clearTimeout(timer); debug({ hookError: String(e), command }); finish(null); });
      child.on('close', (code) => { clearTimeout(timer); finish(code); });
      child.stdin.on('error', () => {});
      child.stdin.end(JSON.stringify(payload));
    } catch (err) {
      debug({ hookError: String(err), command });
      finish(null);
    }
  });
}

function groupMatches(group, toolName) {
  if (toolName === undefined || !group.matcher) return true;
  try { return new RegExp('^(?:' + group.matcher + ')$').test(toolName); } catch { return false; }
}

// Runs commands sequentially; stops at the first exit 2 (block).
async function runGroups(eventName, payload, toolName) {
  const groups = (CFG.claudeHooks && CFG.claudeHooks.hooks && CFG.claudeHooks.hooks[eventName]) || [];
  const stdouts = [];
  for (const g of groups) {
    if (!groupMatches(g, toolName)) continue;
    for (const h of g.hooks || []) {
      if (!h || h.type !== 'command') continue;
      const r = await runCmd(h.command, payload, h.timeout);
      debug({ hook: eventName, command: h.command, code: r.code });
      if (r.code === 2) return { blocked: true, reason: r.stderr.trim() || 'blocked by hook', command: h.command, stdouts };
      if (eventName === 'Stop' && r.code === 0 && r.stdout.trim()) {
        // Claude Stop JSON protocol: exit 0 with {"decision":"block","reason":...} (e.g. kookr-stop-nudge).
        try {
          const j = JSON.parse(r.stdout.trim());
          if (j && j.decision === 'block') return { blocked: true, reason: String(j.reason || 'blocked by hook'), command: h.command, stdouts };
        } catch { /* plain stdout: not a decision */ }
      }
      if (r.code === 0 && r.stdout.trim()) stdouts.push(r.stdout.trim());
    }
  }
  return { blocked: false, reason: '', stdouts };
}

function capitalise(name) {
  const s = String(name || 'unknown');
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function mapTool(tool, args) {
  const a = args && typeof args === 'object' ? args : {};
  if (tool === 'bash') return { tool_name: 'Bash', tool_input: { command: a.command, ...(a.description ? { description: a.description } : {}) } };
  return { tool_name: capitalise(tool), tool_input: a };
}

export const Kookr = async (ctx) => {
  let started = false;
  let stopReprompts = 0;
  let reentry = false;
  let sessionContext = '';
  let last = null;
  const callArgs = new Map();

  const send = async (hook_event_name, extra) => {
    try {
      if (hook_event_name === 'SessionStart') {
        if (started) return;
        started = true;
      }
      if (hook_event_name === 'Stop' && last === 'Stop') return;
      last = hook_event_name;
      const payload = {
        session_id: CFG.sessionId,
        hook_event_name,
        cwd: CFG.cwd,
        transcript_path: '',
        ...(extra || {}),
      };
      debug({ emit: hook_event_name, tool: payload.tool_name });
      await emit(payload);
    } catch (err) {
      debug({ sendError: String(err) });
    }
  };

  await send('SessionStart', { source: 'startup' });
  try {
    const r = await runGroups('SessionStart', {
      session_id: CFG.sessionId, hook_event_name: 'SessionStart', cwd: CFG.cwd, transcript_path: '', source: 'startup',
    });
    sessionContext = r.stdouts.join('\\n');
  } catch (err) { debug({ sessionStartError: String(err) }); }

  return {
    'experimental.chat.system.transform': async (_input, output) => {
      try {
        if (sessionContext && output && Array.isArray(output.system)) output.system.push(sessionContext);
      } catch { /* fail open */ }
    },
    'chat.message': async (_input, output) => {
      try {
        const parts = (output && output.parts) || [];
        const prompt = parts
          .filter((p) => p && p.type === 'text' && typeof p.text === 'string')
          .map((p) => p.text)
          .join('\\n');
        await send('UserPromptSubmit', { prompt });
      } catch { /* fail open */ }
    },
    'tool.execute.before': async (input, output) => {
      let block = null;
      try {
        const args = (output && output.args) || {};
        if (input && input.callID) callArgs.set(input.callID, args);
        const mapped = mapTool(input && input.tool, args);
        await send('PreToolUse', mapped);
        const r = await runGroups('PreToolUse', {
          session_id: CFG.sessionId, hook_event_name: 'PreToolUse', cwd: CFG.cwd, transcript_path: '', ...mapped,
        }, mapped.tool_name);
        if (r.blocked) { block = r.reason; }
      } catch { /* fail open */ }
      if (block !== null) throw new Error(block);
    },
    'tool.execute.after': async (input, output) => {
      try {
        const args = (input && input.args) || (input && input.callID && callArgs.get(input.callID)) || {};
        if (input && input.callID) callArgs.delete(input.callID);
        const mapped = mapTool(input && input.tool, args);
        const out = output && (output.output !== undefined ? output.output : output.title);
        const post = { ...mapped, tool_response: out === undefined ? '' : out };
        await send('PostToolUse', post);
        await runGroups('PostToolUse', {
          session_id: CFG.sessionId, hook_event_name: 'PostToolUse', cwd: CFG.cwd, transcript_path: '', ...post,
        }, mapped.tool_name);
      } catch { /* fail open */ }
    },
    event: async ({ event }) => {
      try {
        const type = event && event.type;
        debug({ event: type });
        if (type === 'session.created') await send('SessionStart', { source: 'startup' });
        else if (type === 'session.idle') {
          await send('Stop');
          const sid = event.properties && event.properties.sessionID;
          const r = await runGroups('Stop', {
            session_id: CFG.sessionId, hook_event_name: 'Stop', cwd: CFG.cwd, transcript_path: '', stop_hook_active: reentry,
          });
          if (r.blocked && stopReprompts < CFG.maxStopReprompts && sid && ctx && ctx.client) {
            stopReprompts += 1;
            // stop_hook_active tells the once-per-session Stop hooks (nb retrospective, completion nudge)
            // to stand down. Kookr's own Stop hooks are mutually exclusive in that sense: each is bounded
            // by its own durable guard (gate cap, nudge marker, retro sentinel), so one blocking must not
            // silence the others on the Stop that follows, or the retrospective / nudge never run.
            reentry = !/kookr-opencode-gate|kookr-stop-nudge|nb-retro/.test(String(r.command || ''));
            debug({ stopReprompt: stopReprompts, reason: r.reason });
            await ctx.client.session.prompt({ path: { id: sid }, body: { parts: [{ type: 'text', text: r.reason }] } });
          } else {
            if (r.blocked) debug({ stopRepromptSkipped: stopReprompts });
            reentry = false;
          }
        }
        else if (type === 'session.error') await send('StopFailure');
        else if (type === 'permission.asked' || type === 'permission.updated') await send('PermissionRequest');
        // TODO: UserPromptSubmit is emitted from the 'chat.message' hook; if a
        // build stops exposing it, derive it from 'message.updated' (role user).
      } catch { /* fail open */ }
    },
  };
};
`;
}
